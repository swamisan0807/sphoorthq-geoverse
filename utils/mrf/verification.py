"""Exhaustive proof that build_qubo()/qubo_energy() reproduce energy()
exactly, and that solve_graph_cut() finds the true global optimum - not
spot-checked against a handful of random assignments (see
tests/test_mrf_energy.py for those), but over EVERY possible binary
labeling of a patch. This is the evidence behind the claim "the QUBO
reformulation is exact, not an approximation of the MRF energy" - the
thing a QAOA run is benchmarked against is provably the same objective,
not a stand-in that merely looks similar.

Practical only up to MAX_EXHAUSTIVE_N pixels (2**n states, held in memory
at once) - deliberately the same ceiling utils.qml.classiq_qaoa.MAX_QUBITS
enforces for a real QAOA run, so a patch small enough to run on QAOA is
also small enough to exhaustively verify end to end. A larger patch (e.g.
the 6x6/8x8 tiers in experiments/) is instead validated by comparing
solve_graph_cut()'s result to QAOA's best-observed bitstring - graph cut
stays exact by construction (Greig/Porteous/Seheult 1989) at any size, it
is only the brute-force enumeration here that stops scaling.
"""

from dataclasses import asdict, dataclass

import numpy as np

from utils.mrf.energy import PatchEnergy, build_qubo, energy as mrf_energy, solve_graph_cut

MAX_EXHAUSTIVE_N = 20  # 2**20 states * n columns of int64 is ~160MB - the practical ceiling for holding every labeling in memory at once


@dataclass
class VerificationResult:
    n: int
    n_states: int
    max_abs_qubo_energy_diff: float  # max |energy(x) - qubo_energy(x)| over EVERY possible x - proves the QUBO reformulation is exact, not just close
    brute_force_min_energy: float
    brute_force_argmin: list[int]
    graph_cut_energy: float
    graph_cut_matches_brute_force_optimum: bool

    def to_dict(self) -> dict:
        return asdict(self)


def exhaustive_equivalence_check(problem: PatchEnergy) -> VerificationResult:
    n = problem.n
    if n > MAX_EXHAUSTIVE_N:
        raise ValueError(
            f"exhaustive check capped at {MAX_EXHAUSTIVE_N} pixels (2**{MAX_EXHAUSTIVE_N} states), got {n} "
            "- graph cut is still exact at this size, only brute-force enumeration stops scaling"
        )

    qubo, const = build_qubo(problem)

    # Every row of `states` is one of the 2**n possible binary labelings,
    # generated by unpacking 0..2**n-1 to bits - vectorized so this stays
    # fast at n=16..20, not a 65k+ -iteration Python loop.
    n_states = 2**n
    all_ints = np.arange(n_states, dtype=np.uint32)
    states = ((all_ints[:, None] >> np.arange(n, dtype=np.uint32)[None, :]) & 1).astype(np.int64)

    unary = np.where(states == 1, problem.unary1[None, :], problem.unary0[None, :]).sum(axis=1)
    pairwise = np.zeros(n_states)
    for (i, j), w in zip(problem.edges, problem.weights):
        pairwise += w * (states[:, i] != states[:, j])
    direct_energy = unary + pairwise

    # The same states, scored via the QUBO build_qubo() returned - this is
    # the thing under test: does it equal direct_energy exactly, for every
    # single one of the 2**n states, not just the ones a solver happens to
    # visit?
    qubo_e = np.full(n_states, const)
    for (i, j), coeff in qubo.items():
        if i == j:
            qubo_e += coeff * states[:, i]
        else:
            qubo_e += coeff * states[:, i] * states[:, j]

    max_abs_diff = float(np.max(np.abs(direct_energy - qubo_e)))

    best_idx = int(np.argmin(direct_energy))
    brute_force_min = float(direct_energy[best_idx])
    brute_force_argmin = states[best_idx].tolist()

    cut_labels = solve_graph_cut(problem)
    cut_energy = mrf_energy(problem, cut_labels)

    return VerificationResult(
        n=n,
        n_states=n_states,
        max_abs_qubo_energy_diff=max_abs_diff,
        brute_force_min_energy=brute_force_min,
        brute_force_argmin=brute_force_argmin,
        graph_cut_energy=cut_energy,
        graph_cut_matches_brute_force_optimum=abs(cut_energy - brute_force_min) < 1e-9,
    )
